#!/usr/bin/env python3
"""Publish a bounded, static editorial edition from pinned repository evidence.

No models run here. Numeric views are projections of existing aggregate exports.
Run from any directory; --check compares regenerated bytes without writing them.
"""
import argparse
import csv
import hashlib
import html
import json
from pathlib import Path
import subprocess

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
OUT = ROOT / 'index/public-2050'
esc = html.escape


def build():
    content = json.loads((HERE / 'content.json').read_text())
    ref = content['source_commit']
    assert len(ref) == 40 and all(c in '0123456789abcdef' for c in ref)
    base = f'https://github.com/fm58cn6g4d-stack/project-2050/blob/{ref}/'
    sources = {s[0] for stop in content['stops'] for s in stop['sources']}
    sources.update(['index/data/fiscal-paths.csv', 'index/fiscal-long-term-model.md', 'index/tools/readme.md', 'sources/family-comparison-model-checks.json',
                    'index/tools/child-poverty/adopted-package.json'])
    domains = sorted((ROOT / 'domains').glob('domain-*.md'))
    sources.update(str(p.relative_to(ROOT)) for p in domains)
    hashes = {}
    # A stale editorial edition must not silently pick up new policy or model bytes.
    for path in sorted(sources):
        data = (ROOT / path).read_bytes()
        pinned = subprocess.check_output(['git', 'show', f'{ref}:{path}'], cwd=ROOT)
        if data != pinned:
            raise ValueError(f'Source changed: {path}; review claims and update source_commit explicitly')
        hashes[path] = hashlib.sha256(data).hexdigest()
    with (ROOT / 'index/data/fiscal-paths.csv').open() as f:
        fiscal = [r for r in csv.DictReader(f) if r['scenario'] == 'DEC' and r['year'] == '2040']
    assert len(fiscal) == 1
    gap = float(fiscal[0]['gf_primary'])  # $B nominal, positive = deficit
    if gap <= 0:
        raise ValueError('Financing copy needs editorial review: no longer a positive gap')
    results = json.loads((ROOT / 'sources/family-comparison-model-checks.json').read_text())
    selected = json.loads((ROOT / 'index/tools/child-poverty/adopted-package.json').read_text())
    assert selected == results['adopted_package']
    assert selected['new_voucher_awards'] == 1000000 and selected['credit_policy'] == 'FAM-1D'
    assert results['source_income_year'] == 2025 and results['valuation_year'] == 2034
    cases = results['adopted_cases']
    assert [c['delivery'] for c in cases] == ['moderate', 'enhanced', 'full']
    assert all(c['award_cap'] == 1000000 and c['design'] == 'AFA_2025_real' for c in cases)

    def link(path, label):
        return f'<a href="{base}{esc(path, quote=True)}">{esc(label)}</a>'

    def compare():
        rows = ''.join(f'<tr><th scope="row">{esc(c["delivery"].capitalize())}</th>'
                       f'<td>{100*c["result"]["poor_rate"]:.2f}%</td>'
                       f'<td>{100*c["result"]["deep_poor_rate"]:.2f}%</td></tr>' for c in cases)
        baseline = 100 * cases[0]['baseline']['poor_rate']
        return f'''<div class="table-scroll"><table><caption>Selected channels, different delivery assumptions</caption>
        <thead><tr><th scope="col">Research case</th><th scope="col">Child SPM poverty</th><th scope="col">Deep poverty</th></tr></thead>
        <tbody>{rows}</tbody></table></div><p>Same-scenario baseline: {baseline:.2f}% child poverty.
        These are conditional results for the credit, care/pre-K expense relief, meals and housing channels, using 2025 source income and a 2034 valuation reference.
        They are not forecasts of 2050, full-agenda effects or three adopted delivery rates. Deep poverty means resources below half the SPM threshold.</p>
        <p>These results do not incorporate the full health, paid-leave, tax or earnings effects of the agenda.
        The annual AFA analogue, legal-eligibility proxies and assumed receipt and lease-up limit the comparison.
        The linked report and JSON record conditional sampling uncertainty; it does not cover model or policy uncertainty.
        Near-eradication remains an ambition, not a result established here.</p>
        <p>{link('sources/family-comparison-model-checks.json', 'Inspect aggregate results and uncertainty')}</p>'''

    stops = content['stops']
    ids = [s['id'] for s in stops]
    assert len(ids) == len(set(ids)) == 6
    assert all(r in ids for s in stops for r in s['related'])
    def stoplink(stop, map_link=False):
        label = stop['number'] if map_link else f'<b>{stop["number"]}</b> {esc(stop["place"])}'
        return f'<a class="{"map-link" if map_link else "stop-link"}" data-stop="{stop["id"]}" href="#{stop["id"]}" aria-label="{esc(stop["place"])}">{label}</a>'
    chapters = []
    for s in stops:
        references = ''.join(f'<li>{link(path, label)}<small>{esc(kind)}</small></li>' for path, label, kind in s['sources'])
        related = ''.join(stoplink(next(t for t in stops if t['id'] == rid)) for rid in s['related'])
        chapters.append(f'''<article class="chapter" id="{s['id']}" aria-labelledby="title-{s['id']}">
        <p class="eyebrow">{s['number']} / {esc(s['place'])}</p><h2 id="title-{s['id']}" tabindex="-1">{esc(s['title'])}</h2>
        <span class="tag">Fictional scene · possible 2050</span><p class="scene">{esc(s['scene'])}</p>
        <p>{esc(s['connection'])}</p><h3 class="small-title">The choices behind it</h3><p>{esc(s['policy'])}</p>
        <div class="condition"><h3 class="small-title">What still has to work</h3><p>{esc(s['condition'])}</p></div>
        <p class="question">{esc(s['question'])}</p><details class="evidence"><summary>Open the evidence &amp; policy notes</summary>
        <p>Project choices are not enacted law. These records show the design, its basis and its limits at this edition's source commit.</p>
        <ul class="sources">{references}</ul>{compare() if s['id'] == 'home' else ''}</details>
        <div class="related"><span>Follow the connection →</span>{related}</div></article>''')
    agenda = ''.join('<li>' + link(str(p.relative_to(ROOT)), 'AI' if p.stem == 'domain-ai' else p.stem.removeprefix('domain-').replace('-', ' ').capitalize()) + '</li>' for p in domains)
    agenda += '<li>' + link('domains/transportation-moving-america-act-2031-draft-2.md', 'Transportation') + '</li>'
    css = (HERE / 'style.css').read_text()
    js = (HERE / 'interaction.js').read_text()
    svg = (HERE / 'community.svg').read_text()
    page = f'''<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="description" content="Explore a possible Project 2050 community and the policies, evidence and unresolved choices behind it. Internal design prototype.">
<title>A day in a possible 2050 · Project 2050</title><style>{css}</style></head><body>
<a class="skip" href="#experience">Skip to the experience</a><header><div class="shell header">
<a class="brand" href="#"><span class="brand-mark">2050</span>Project 2050</a>
<nav aria-label="Main"><a href="#experience">Explore</a><a href="#path">The path</a><a href="#agenda">Policy &amp; evidence</a></nav></div></header>
<main class="shell"><div class="intro"><div><span class="eyebrow">A fair shot at a good life</span>
<h1>A day in a<br>possible 2050.</h1></div><div><span class="tag">Design prototype · October 24, 2026</span>
<p>More room to make plans. Care you can depend on. A place in the decisions that shape your life.
Explore the choices that could make that future possible—and the work still ahead.</p></div></div>
<p class="notice">This community is fictional. Its places open real project proposals and evidence; they do not predict local outcomes or determine anyone's benefits.</p>
<section class="journey" id="experience" aria-label="Explore six places"><div class="map-wrap">
<div class="map">{svg}<span class="map-caption">One imagined place.<br>Many connected choices.</span>{''.join(stoplink(s, True) for s in stops)}</div>
<nav aria-label="Places in the community"><ol class="map-legend">{''.join('<li>'+stoplink(s)+'</li>' for s in stops)}</ol></nav>
<p class="notice">Choose a numbered place or use the text links. This is a schematic illustration, not a geographic map. No local projects are implied.</p>
</div><div class="chapters">{''.join(chapters)}</div></section>
<section id="path" class="section"><span class="eyebrow">From a picture to a program</span><h2>How could we get there?</h2>
<p class="section-intro">The picture asks what a good life could feel like. The governing program has to explain who acts, what it costs, what can fail and how people can obtain a correction.</p>
<div class="horizon"><div><strong>2029–30</strong><p>Enactment and early delivery. Prepare legislation, funding and institutions together. Political assumptions are planning stipulations, not election forecasts.</p></div>
<div><strong>2030–33</strong><p>Scale services and assistance. The voucher plan phases one million total new awards over these years. Awards are not successful leases.</p></div>
<div><strong>2040</strong><p>Permanent programs must be funded at maturity and afterward. The current working fiscal model fails that requirement.</p></div>
<div><strong>2050</strong><p>Ask what lasted, who was left out and what needs to change. This is a horizon for inquiry, not a forecast produced by the illustration.</p></div></div>
<div class="finance"><div><span class="eyebrow">Financing remains unresolved</span><span class="amount">≈ ${gap:.0f}B</span><p>FY2040 general-fund primary gap<br>Working fiscal case · nominal dollars</p></div>
<div><p>The adopted family package is included in the current model. A financing strategy that satisfies the project's fiscal rule is still under redesign. None of the three recent financing illustrations has been selected.</p>
<p>This figure comes from the DEC case; it is not the full federal deficit, an official score or the cost of the whole agenda. The agency-surge cash path remains a proxy, and some policy costs remain unpriced.</p>
<p>{link('index/fiscal-long-term-model.md', 'Read the fiscal analysis')} · {link('governing/project-2050-governing-decisions.md', 'Read the governing choices')}</p></div></div>
<p class="notice">This path separates policy timing from household receipt. It does not move MOV-31 out of the second Congress or change any health launch date.</p></section>
<section id="agenda" class="section"><span class="eyebrow">The wider agenda</span><h2>Enter through the question you bring.</h2>
<p class="section-intro">These six places are a beginning. The professional layer covers the full program, including questions this community cannot represent. Open a policy home to inspect its selected design, alternatives and dependencies.</p>
<ul class="agenda">{agenda}</ul><p>{link('governing/project-charter.md', 'Read the project charter')} · {link('index/tools/readme.md', 'Inspect the models and reproduction commands')}</p>
<p class="notice">Repository links open the pinned source edition and may require GitHub access. The explanation and key limitations remain readable here.</p></section>
<section class="section"><h2>What would make this direction useful?</h2><p class="section-intro">For this design review: can you distinguish the imagined future, the selected policy and the unresolved condition? Can you reach the evidence you would need to challenge the account?</p>
<a class="review-link" href="directions.html">Compare the three editorial directions →</a></section></main>
<footer><div class="shell">Internal review prototype · No public deployment · Source edition {esc(content['edition_date'])} · Commit {ref}<br>
Authored illustration. Navigation changes the place you are reading; no personal data is collected and no outcome is recalculated.
<a href="manifest.json">Source and build manifest</a></div></footer><script>{js}</script></body></html>
'''
    directions = (HERE / 'directions.html').read_text().replace('{{STYLE}}', css)
    outputs = {'index.html': page.encode(), 'directions.html': directions.encode()}
    for p in sorted(HERE.iterdir()):
        if p.is_file() and p.suffix in {'.py', '.json', '.css', '.js', '.cjs', '.svg', '.html', '.md'}:
            hashes[str(p.relative_to(ROOT))] = hashlib.sha256(p.read_bytes()).hexdigest()
    manifest = {'schema_version': 1, 'status': 'internal_design_prototype_not_public_release',
                'source_commit': ref, 'edition_date': content['edition_date'],
                'numeric_contracts': {
                    'fiscal_gap': {'path': 'index/data/fiscal-paths.csv', 'selector': {'scenario':'DEC','year':'2040'}, 'field':'gf_primary','unit':'nominal USD billion','positive':'deficit','value':gap},
                    'poverty': {'path':'sources/family-comparison-model-checks.json','selector':'adopted_cases', 'source_income_year':2025,'valuation_year':2034,'kind':'conditional_selected_channels_not_forecast'}},
                'sha256': hashes, 'outputs_sha256': {k:hashlib.sha256(v).hexdigest() for k,v in outputs.items()}}
    outputs['manifest.json'] = (json.dumps(manifest, indent=2, sort_keys=True)+'\n').encode()
    return outputs


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    products = build()
    if args.check:
        stale = [name for name, data in products.items() if not (OUT/name).exists() or (OUT/name).read_bytes() != data]
        if stale:
            raise SystemExit('Stale products: '+', '.join(stale))
        print('Public prototype: generated bytes and pinned sources verified')
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, data in products.items():
            (OUT/name).write_bytes(data)
        print('Built '+', '.join(products))
