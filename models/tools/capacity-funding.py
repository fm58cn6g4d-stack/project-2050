"""Separate CAP-7S funding availability from the interim cash model.
Blank FY2029 cash is unknown, not zero. No new score is manufactured.
"""
import json
from pathlib import Path
from inputs import read

def assess(funding, bill, years):
    if funding["available_on_enactment"] != "yes" or funding["multi_year"] != "yes":
        raise ValueError("CAP-7S must be multi-year and immediately available")
    if funding["target_vehicle"] != bill["rail"]:
        raise ValueError("Surge target differs from ledger vehicle")
    total_bn = bill["cost_mid"] * 1000
    cash = [float(years[f"y{y}"]) for y in range(2030, 2040)]
    if abs(sum(cash) - total_bn) > 0.001:
        raise ValueError("Interim cash profile no longer matches lifetime working amount")
    if funding["fy2029_outlay_bn"].strip() or funding["outlay_status"] != "unpriced":
        raise ValueError("A priced FY2029 path needs lifetime/window and fiscal-engine reconciliation; do not normalize it away")
    if funding["byrd_status"] != "pending":
        raise ValueError("Eligibility certification requires a separate reviewed change")
    return dict(id="CAP-7S", availability_fy=int(funding["availability_fy"]),
                target_vehicle=funding["target_vehicle"], available_bn=total_bn,
                fy2029_outlay_bn=None, cash_profile_status="interim_proxy",
                fiscal_validation="incomplete_for_acceleration",
                byrd_status="pending", proxy_cash_bn=dict(zip(range(2030,2040),cash)))

def main():
    ledger=json.loads(Path("ledger.json").read_text())
    bill=next(b for b in ledger["bills"] if b["id"]=="CAP-7S")
    funding=next(r for r in read("capacity-funding.csv") if r["id"]=="CAP-7S")
    years=next(r for r in read("fiscal-years.csv") if r["id"]=="CAP-7S")
    r=assess(funding,bill,years)
    lines=["# Agency surge: funding availability and cash spending","",
           "*Generated by models/tools/capacity-funding.py. Do not hand-edit. Amounts below are billions of dollars; lifetime funding is distinct from the 2030-39 display.*","",
           f"**Decided Oct 21:** all CAP-7S multi-year funding is available immediately on enactment, targeting {r['target_vehicle']} in FY{r['availability_fy']}. Provisional lifetime amount: ${r['available_bn']:g}B. This is not a requirement or forecast to spend it all immediately.","",
           "**FY2029 cash is unpriced, not zero.** No percentage is silently assigned and no new borrowing allowance is assumed. Agency allocations remain provisional. Eligibility and committee jurisdiction remain pending; the R1 vote simulation assumes this target is legally available.","",
           "| FY | Funding availability | Cash outlays |","| --- | --- | --- |",
           f"| 2029 | Full ${r['available_bn']:g}B on enactment, subject to legal funding mechanics | Unpriced |"]
    for y,v in r["proxy_cash_bn"].items():
        lines.append(f"| {y} | No new funding; final obligation period to be drafted | ${v:g}B, interim proxy |")
    lines+=["","The old cash proxy totals ${:g}B in 2030-39. It is retained for comparison, not a validated accelerated spending path.".format(r["available_bn"]),"",
            "## What the main fiscal results do and do not show","",
            "The fiscal engine still normalizes CAP-7S to its old 2030-39 total. Until FY2029 and later cash are costed, its debt, interest and D4 results are conditional on that proxy. They do not establish that the accelerated cash path passes D4.","",
            "For a fixed lifetime total, moving $X of outlays into FY2029 reduces later outlays by $X; it is not an extra $X on top. Show FY2029 separately, update the 2030-39 ledger sum and C42, and recalculate debt, interest and the annual investment envelope. Do not auto-normalize the remaining window back to $600B. Availability of budget authority alone is not cash spending.","",
            "Permanent CAP-7 operations, finite CAP-7S setup, state implementation and HLT administrative allowances remain separate. CMS's annex and unpriced cost register are in legacy/domains/domain-capacity.md and legacy/sources/health-cms-implementation-cost-register.csv."]
    Path("capacity-funding-model.md").write_text("\n".join(lines)+"\n")
    Path("capacity-funding.json").write_text(json.dumps(r,indent=2)+"\n")
    print("capacity: full surge available FY2029; cash unpriced; fiscal acceleration validation incomplete")
if __name__=="__main__":main()

