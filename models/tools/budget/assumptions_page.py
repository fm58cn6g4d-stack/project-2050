#!/usr/bin/env python3
"""assumptions_page.py: write the plain-language assumptions page from the register.

Reads models/data/budget/assumptions.csv (one row per assumption the fiscal models use, B1 of
models/tools/budget/WORKFLOW.md) and writes models/tools/budget/assumptions.md, grouped by topic in
the order topics first appear in the register. run-all.sh runs it into build/ and the drift check
compares the result with the committed page, so the page never drifts from the register.

  python3 models/tools/budget/assumptions_page.py [--csv PATH] [--out PATH]
"""
import argparse
import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CSV = ROOT / 'models/data/budget/assumptions.csv'
OUT = ROOT / 'models/tools/budget/assumptions.md'
COLUMNS = ['id', 'topic', 'label', 'value', 'unit', 'where', 'source', 'decided_by', 'matters', 'notes']
ASM_ID = re.compile(r'^ASM-[A-Z0-9]+(?:-[A-Z0-9]+)*$')
LEVELS = ('high', 'medium', 'low')


def read(path):
    with open(path, newline='') as f:
        reader = csv.DictReader(f)
        missing = [c for c in COLUMNS if c not in (reader.fieldnames or [])]
        if missing:
            sys.exit(f'{path}: missing column(s) {", ".join(missing)}')
        return list(reader)


def problems(rows):
    """Format errors in the register (the registry checker runs the same function)."""
    out, seen = [], set()
    for n, r in enumerate(rows, 2):
        where = f'assumptions.csv line {n} ({r.get("id") or "no id"})'
        if not ASM_ID.match(r.get('id', '')):
            out.append(f'{where}: id must look like ASM-CPI-PATH')
        if r.get('id') in seen:
            out.append(f'{where}: defined twice')
        seen.add(r.get('id'))
        for c in ('topic', 'label', 'value', 'where', 'source', 'decided_by', 'matters'):
            if not r.get(c, '').strip():
                out.append(f'{where}: {c} is empty')
        if r.get('matters') and not r['matters'].startswith(tuple(l + ':' for l in LEVELS)):
            out.append(f'{where}: matters must start "high:", "medium:" or "low:" and give a reason')
    return out


def level(r):
    return r['matters'].split(':', 1)[0]


def page(rows):
    topics = list(dict.fromkeys(r['topic'] for r in rows))
    count = {l: sum(level(r) == l for r in rows) for l in LEVELS}
    unrecorded = [r for r in rows if level(r) == 'high' and r['decided_by'].startswith('unrecorded')]
    lines = [
        '# Budget model: assumptions',
        '',
        '*Generated by `models/tools/budget/assumptions_page.py` from `models/data/budget/assumptions.csv`. '
        'Do not edit by hand: change the register and rerun `bash models/tools/run-all.sh --write`.*',
        '',
        'Role: every assumption the fiscal models use now, in plain language, with where it lives, its source, '
        'who decided it and how much it matters. Status: current register (B1 of `models/tools/budget/WORKFLOW.md`). '
        'How the project counts is in `models/tools/budget/CONVENTIONS.md`. Nothing here changes a model input.',
        '',
        f'**{len(rows)} assumptions:** {count["high"]} matter a lot, {count["medium"]} somewhat, {count["low"]} little. '
        'Amounts are in billions of nominal dollars by fiscal year ($B) or ten-year totals for 2030-39 in trillions '
        '($T), as the unit says. Positive amounts raise the deficit.',
        '',
    ]
    if unrecorded:
        lines += ['**High-impact assumptions with no recorded decision** (set in code or an input table; no '
                  '`DEC-` entry or decision brief names them):', '']
        lines += [f'- {r["id"]}: {r["label"]}' for r in unrecorded]
        lines.append('')
    lines += ['## Contents', '']
    lines += [f'- {t} ({sum(r["topic"] == t for r in rows)})' for t in topics]
    for t in topics:
        lines += ['', f'## {t}', '']
        for r in (r for r in rows if r['topic'] == t):
            value = r['value'] + (f' ({r["unit"]})' if r['unit'] else '')
            lines += [f'### {r["id"]}', '', r['label'] + '.', '',
                      f'- **Value:** {value}',
                      f'- **How much it matters:** {r["matters"]}',
                      f'- **Where:** {r["where"]}',
                      f'- **Source:** {r["source"]}',
                      f'- **Decided by:** {r["decided_by"]}']
            if r['notes']:
                lines.append(f'- **Notes:** {r["notes"]}')
            lines.append('')
    return '\n'.join(lines).rstrip('\n') + '\n'


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--csv', default=str(CSV))
    ap.add_argument('--out', default=str(OUT))
    a = ap.parse_args()
    rows = read(a.csv)
    errs = problems(rows)
    if errs:
        sys.exit('\n'.join(errs))
    Path(a.out).write_text(page(rows))
    print(f'wrote {a.out}: {len(rows)} assumptions')


if __name__ == '__main__':
    main()
