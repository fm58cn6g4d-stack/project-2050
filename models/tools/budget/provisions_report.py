#!/usr/bin/env python3
"""provisions_report.py: write models/tools/budget/provisions.md from the provision specs.

Role: the plain-language summary of models/data/budget/provisions.csv (piece B3): how many
ledger rows are each kind and vehicle, how their budget authority is known, which fields are
unknown, and where the files disagree. run-all.sh writes it into build/ and the drift check
compares it with the committed page. Status: current. Standard library only.

  python3 models/tools/budget/provisions_report.py [--ledger build/ledger.json] [--out PATH]
"""
import argparse, os, sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", ".."))
sys.path.insert(0, HERE)
import provisions as P  # noqa: E402

KIND_WORDS = {"discretionary": "Discretionary appropriation",
              "contract_authority": "Contract authority (mandatory budget authority, discretionary outlays)", "mandatory": "Mandatory (direct) spending",
              "revenue": "Revenue", "transfer": "Interest-neutral transfer (self-funded)",
              "none": "No direct budget effect"}
VEHICLE_WORDS = {"reconciliation": "Reconciliation (R1, R2, R3)", "regular_order": "Regular-order authorization",
                 "regular_appropriations": "Regular (annual) appropriations",
                 "supplemental_emergency": "Supplemental or emergency appropriations",
                 "advance_appropriation": "Advance appropriation", "none": "Not a provision (financing line or feedback)",
                 "unknown": "Unknown"}
BA_WORDS = {"spendout": "Derived from outlays at B2's discretionary spend-out rates (rough)",
            "contract_authority": "Contract authority from the transportation model, plus spend-out for the rest (rough)",
            "outlays": "Equal to outlays (a benefit, entitlement or tax credit)",
            "on_enactment": "Provided in full on enactment; amount not priced",
            "none": "None (revenue, or no budget effect)", "unknown": "Unknown"}
APPR_WORDS = {"annual": "Annual appropriation", "contract_authority": "Contract authority, limited by annual obligation limits", "subject_to_appropriation": "Authorized, subject to later appropriation",
              "direct_spending": "Direct spending provided by the law itself", "multi_year": "Multi-year appropriation",
              "advance": "Advance appropriation", "none": "None", "unknown": "Unknown"}
FIELDS = ("category", "vehicle", "appropriation", "budget_authority", "start", "ramp", "indexation",
          "expiry", "continues_after_2039", "unified")


def fmt_t(v):
    return "%.2f" % v if abs(v) >= 0.005 else ("0" if v == 0 else "%.3f" % v)


def table(head, body):
    out = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in body]
    return out


def ids(xs):
    xs = list(xs)
    return ", ".join(xs) if xs else "none"


def render(ledger_path):
    S = P.specs()
    SC = P.score_all(ledger_path)
    rows = [s for s in S.values() if s["table"] != "component"]
    scored = [s for s in rows if s["in_model"] == "yes"]
    menu = [s for s in rows if s["in_model"] == "no"]
    comps = [s for s in S.values() if s["table"] == "component"]
    o = []
    o.append("# Provision specs: how the ledger's money is enacted")
    o.append("")
    o.append("Role: a summary of `models/data/budget/provisions.csv`, the provision spec for every ledger row (piece B3 of `models/tools/budget/WORKFLOW.md`). It shows where the model's picture of how money is enacted is still thin. Status: generated by `models/tools/budget/provisions_report.py` from the specs and the current ledger; do not edit by hand. The method is in `models/tools/budget/provisions.py` and the format in `models/data/budget/README.md`, \"Provision specs\".")
    o.append("")
    o.append("**What this changes.** Nothing in any figure. For every row the fiscal model scores, the library produces the same path, year by year, as `models/tools/fiscal-model.py`, the same floating-point number in every year from FY2026 to FY2056; each row's FY2030-39 total equals its ledger midpoint; and `models/data/fiscal-paths.csv` is unchanged. `models/tools/budget/test_provisions.py` checks all three on every run. What B3 adds is the budget-concept reading: kind, vehicle, appropriation type and budget authority.")
    o.append("")
    o.append("## The rows")
    o.append("")
    o.append("The ledger has %d rows: %d bills, %d revenue options, %d gap-closing options and %d dynamic-feedback rows. One bill, HOU-1, is split into %d components, each with its own spec. The fiscal model scores %d of the rows; the other %d are on the revenue menu, outside the general fund, or are borrowing lines whose spending sits in other rows." % (
        len(rows), sum(s["table"] == "bill" for s in rows), sum(s["table"] in ("base_revenue", "revenue_option") for s in rows),
        sum(s["table"] == "option" for s in rows), sum(s["table"] == "dynamic" for s in rows), len(comps), len(scored), len(menu)))
    o.append("")
    o.append("### By kind")
    o.append("")
    o.append("Ten-year amounts are FY2030-39 deficit effects in trillions on the unified basis (positive raises the deficit), for the bills and the revenue base; options and dynamic rows are not in the decided totals and are shown as counts only.")
    o.append("")
    body = []
    for k in P.KINDS:
        n_all = sum(s["kind"] == k for s in rows)
        n_in = sum(s["kind"] == k for s in scored)
        core = [s["id"] for s in scored if s["kind"] == k and s["table"] in ("bill", "base_revenue")]
        tot = sum(P.window_total(SC[i]["unified"]) for i in core)
        body.append([KIND_WORDS[k], n_all, n_in, len(core), fmt_t(tot)])
    o += table(["Kind", "Rows", "Scored", "Bills and base revenue", "FY2030-39, $T"], body)
    o.append("")
    o.append("### By vehicle")
    o.append("")
    body = []
    for v in P.VEHICLES:
        sel = [s for s in rows if s["vehicle"] == v]
        if not sel:
            body.append([VEHICLE_WORDS[v], 0, 0, "", ""])
            continue
        kinds = Counter(s["kind"] for s in sel)
        body.append([VEHICLE_WORDS[v], len(sel), sum(s["in_model"] == "yes" for s in sel),
                     ", ".join("%s %d" % (k, kinds[k]) for k in P.KINDS if kinds[k]),
                     ids(s["id"] for s in sel) if len(sel) <= 12 else ""])
    o += table(["Vehicle", "Rows", "Scored", "Kinds", "Rows (if few)"], body)
    o.append("")
    o.append("No row is modeled as a supplemental, emergency or advance appropriation: nothing in the ledger or its notes says any is (CONVENTIONS.md, section 4). The vehicle of a bill is its ledger rail; of a revenue or option row, the reconciliation package that `models/data/inputs/votes-bills.csv` assigns it to, where it does.")
    o.append("")
    o.append("### Appropriation type and budget authority (scored spending rows)")
    o.append("")
    spend = [s for s in scored if s["kind"] in ("discretionary", "contract_authority", "mandatory", "transfer")] + comps
    o += table(["Appropriation type", "Rows"], [[APPR_WORDS[a], n] for a, n in Counter(s["appropriation"] for s in spend).most_common()])
    o.append("")
    o += table(["Budget authority", "Rows"], [[BA_WORDS[a], n] for a, n in Counter(s["budget_authority"] for s in spend).most_common()])
    o.append("")
    # discretionary budget authority
    disc = [s["id"] for s in scored if s["budget_authority"] in ("spendout", "contract_authority") and any(SC[s["id"]]["outlays"].values())]
    cover = {i: {y: (1 - SC[i].get("contract_authority_share", 0.0)) * v for y, v in SC[i]["outlays"].items()} for i in disc}
    ba_w = sum(P.window_total(SC[i]["ba_discretionary"]) for i in disc)
    out_w = sum(P.window_total(cover[i]) for i in disc)
    early = sum(SC[i]["ba_discretionary"][y] for i in disc for y in range(P.Y0, P.W0)) / 1000
    gaps = {i: P.spendout_gap(SC[i]["ba_discretionary"], cover[i], S[i]["spendout_group"]) for i in disc}
    worst = sorted(disc, key=lambda i: -max(abs(v) for v in gaps[i].values()))[:5]
    first_share = P._spendout("nondefense")[0]
    worst_cbo = lambda g: max(100 * abs(a / b - 1) for a, b in P.cbo_discretionary_outlays(g).values())
    o.append("**What the discretionary spend-out shows.** For the %d rows with discretionary budget authority, the library estimates that budget authority (the appropriations) behind the model's outlays: each year's appropriation is the outlays it pays for over B2's four-year spend-out. The shares are B2's, calibrated to CBO (`spendout-discretionary-cbo.csv`): OMB's history gives their timing, with ground transportation taken out of nondefense because its outlays run on contract authority (see below), and one scale per group makes CBO's projected budget authority give CBO's projected outlays. Rebuilt that way, CBO's FY2029-36 discretionary outlays come back within %.1f%% for defense and %.1f%% for nondefense, once the nondefense accounts with no discretionary budget authority are carried on their own. Over FY2030-39 that is $%.2f trillion of budget authority for $%.2f trillion of outlays. Another $%.2f trillion would have to be appropriated before FY2030, in FY2027-29: at these rates only %.0f%% of new nondefense budget authority is spent in its first year, so outlays that start at full speed in FY2030, as most profiles have them, need money enacted earlier. The scoring window does not count it (CONVENTIONS.md, choice 3)." % (
        len(disc), worst_cbo("defense"), worst_cbo("nondefense"), ba_w, out_w, early, 100 * first_share))
    o.append("")
    o.append("Spending that budget authority out at the same rates does not give back the model's outlays exactly, because the model's profiles start and stop faster than B2's rates allow. The largest FY2030-39 gaps, in billions: %s. The model's outlays stay canonical; the budget-authority figures are rough, because the shares' timing is OMB history's, not CBO's account-by-account rates (B2 README, \"Spend-out set by CBO's projections\")." % (
        "; ".join("%s %+.1f in FY%d" % (i, gaps[i][y], y) for i in worst for y in [max(gaps[i], key=lambda y: abs(gaps[i][y]))])))
    o.append("")
    ca = [s["id"] for s in scored if s["kind"] == "contract_authority"]
    if ca:
        cbo = [r for r in P.D.table("cbo-contract-authority") if r["group"] == "highway_transit"]
        cav = [float(r["contract_authority"]) for r in cbo]
        cao = [float(r["outlays"]) for r in cbo]
        firsts = ", ".join("FY%d for %s" % (min(y for y, v in SC[i]["ba_mandatory"].items() if v), i) for i in ca)
        o.append("**Contract authority.** Highway and transit programs paid from the Highway Trust Fund get mandatory budget authority (contract authority) from their authorizing law, while annual appropriations acts cap how much may be obligated each year, so their outlays count as discretionary. CBO records them that way: in its February 2026 baseline, FY%s-%s, the trust fund's highway and transit accounts carry about $%.0f billion a year of mandatory contract authority (the FY2026 level, which CBO's baseline extends) and $%.0f-%.0f billion a year of discretionary nondefense outlays (`models/data/budget/cbo-contract-authority.csv`). %s carry the Moving America acts' top-ups to those accounts, and the library records them the same way. %s The rest of each row (rail and transit packages, rail top-ups) is general-fund money and gets discretionary budget authority by spend-out. The model spreads each row's outlays from FY2030, before its first contract authority (%s), and continues 30%% of them after 2039 with no contract authority behind them; the text-and-model differences below say the same." % (
            cbo[0]["year"], cbo[-1]["year"], sum(cav) / len(cav), min(cao), max(cao), " and ".join(ca),
            " ".join("%s: $%.1f billion of contract authority in FY%s, %.0f%% of its FY2030-39 outlays." % (
                i, sum(SC[i]["ba_mandatory"].values()), S[i]["contract_authority_years"], 100 * SC[i]["contract_authority_share"]) for i in ca),
            firsts))
        o.append("")
    o.append("## Unknown fields")
    o.append("")
    o.append("A field is `unknown` where the repository does not say. Nothing was guessed. For the %d scored rows (and the %d HOU-1 components):" % (len(scored), len(comps)))
    o.append("")
    body = []
    for f in FIELDS:
        un = [s["id"] for s in scored + comps if s[f] == P.UNKNOWN]
        body.append(["`%s`" % f, len(un), ids(un) if len(un) <= 30 else "%d rows (see the CSV)" % len(un)])
    o += table(["Field", "Unknown", "Rows"], body)
    o.append("")
    o.append("For the %d rows the model does not score, the profile fields are unknown by construction (no profile exists): %s." % (len(menu), ", ".join(
        "%s %d" % (f, sum(s[f] == P.UNKNOWN for s in menu)) for f in FIELDS if sum(s[f] == P.UNKNOWN for s in menu))))
    o.append("")
    o.append("### Model assumptions with no statement in the ledger")
    o.append("")
    o.append("The model always has a growth index and an end year (or none) for a scored row; that is how it spreads the ten-year amount. Whether the law itself is indexed, or expires, is stated in the ledger's text for only some rows (`indexation_basis` and `expiry_basis` = `stated`, quoted in the row's notes). For the rest the model's value is its own assumption (`model`).")
    o.append("")
    body = []
    for f in ("indexation_basis", "expiry_basis"):
        c = Counter(s[f] for s in scored + comps)
        body.append(["`%s`" % f, c["stated"], c["model"], ids(s["id"] for s in scored + comps if s[f] == "stated")])
    o += table(["Field", "Stated", "Model only", "Stated for"], body)
    o.append("")
    o.append("## Where the files disagree")
    o.append("")
    o.append("These are reported, not fixed: changing a category or a profile changes adopted inputs, which is Espen's decision (tier 3), and B6's work.")
    o.append("")
    for s in rows:
        for part in s["notes"].split(" | "):
            if part.startswith("Conflict") or part.startswith("Text and model differ"):
                o.append("- **%s**: %s." % (s["id"], part.rstrip(".")))
    o.append("")
    return "\n".join(o)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ledger", default=os.path.join(ROOT, "build", "ledger.json"))
    ap.add_argument("--out", default=os.path.join(HERE, "provisions.md"))
    a = ap.parse_args()
    with open(a.out, "w") as f:
        f.write(render(a.ledger))


if __name__ == "__main__":
    main()
