// Role: builds the Figma sync for direction C (stage H step H9) from the same code as the repository's pictures.
// Usage: node models/tools/public-product/design/figma/build_figma_sync.js
// Writes, next to this file:
//   sync.js: one use_figma script that redraws the four C picture frames and relabels the sections (one MCP call);
//   one SVG per frame (c-clinic-phone-390.svg and so on), to drag into the frames by hand if the MCP quota is used up.
// Status: draft, November 26, 2026. The frame sizes are the illustration frames' sizes (phone 390 x 380,
// desktop 720 x 980); an SVG dragged into a frame of another size can be scaled to fit.
const fs = require('fs'), path = require('path');
const { scene } = require('../people/build_people.js');
const here = __dirname, ppl = path.join(here, '../people');

const FRAMES = [
  ['5:616', 'clinic', 'phone-390', 390, 380],
  ['5:683', 'clinic', 'desktop-1440', 720, 980],
  ['5:770', 'home', 'phone-390', 390, 380],
  ['5:836', 'home', 'desktop-1440', 720, 980],
];
for (const [, which, size, W, H] of FRAMES) fs.writeFileSync(path.join(here, `c-${which}-${size}.svg`), scene(which, W, H) + '\n');

// The Figma script carries people.js and build_people.js's scene code inline, and measures each frame at run time.
const people = fs.readFileSync(path.join(ppl, 'people.js'), 'utf8').replace(/^if \(typeof module.*$/m, '');
const b = fs.readFileSync(path.join(ppl, 'build_people.js'), 'utf8');
const sceneCode = b.slice(b.indexOf('const inner'), b.indexOf('if (require.main !== module)'));
const sync = `// Generated by build_figma_sync.js; do not edit by hand. File "Project 2050: A day in 2050", page 02 Directions.
await figma.loadFontAsync({family:'Space Grotesk',style:'Bold'});
${people}
${sceneCode}
const rgb=h=>{h=h.replace('#','');return{r:parseInt(h.slice(0,2),16)/255,g:parseInt(h.slice(2,4),16)/255,b:parseInt(h.slice(4,6),16)/255}};
const RAW=h=>[{type:'SOLID',color:rgb(h)}];
const page=await figma.getNodeByIdAsync('3:3'); await figma.setCurrentPageAsync(page);
const out=[];
for(const id of ${JSON.stringify(FRAMES.map(f => f[0]))}){
  const fr=await figma.getNodeByIdAsync(id); const pic=fr.findOne(n=>n.type==='FRAME'&&n.name.startsWith('Illustration'));
  const which=fr.name.includes('clinic')?'clinic':'home'; const W=Math.round(pic.width),H=Math.round(pic.height);
  const clock=pic.children.find(c=>c.type==='TEXT'); for(const c of [...pic.children]) if(c!==clock) c.remove();
  const n=figma.createNodeFromSvg(scene(which,W,H).replace(/<title>.*?<\\/title>/,'')); n.name='Placeholder picture (people/build_people.js)'; pic.appendChild(n); n.x=0; n.y=0;
  if(clock){ pic.appendChild(clock); clock.fills=RAW('#14213D'); const phone=W<500; clock.fontSize=phone?56:120; clock.x=phone?14:28; clock.y=phone?6:14; }
  pic.name='Illustration · '+which+' (placeholder people, direction C)'; out.push([id,pic.id,W,H]);
}
const names={'7:2':'A · Warm editorial illustration (archived alternate)','7:3':'B · Documentary photo-real (archived alternate)','7:4':'C · Flat graphic (working direction)'};
for(const [id,nm] of Object.entries(names)){ const s=await figma.getNodeByIdAsync(id); if(s) s.name=nm; }
return out;
`;
fs.writeFileSync(path.join(here, 'sync.js'), sync);
console.log('sync.js', sync.length, 'bytes;', FRAMES.length, 'SVGs');
